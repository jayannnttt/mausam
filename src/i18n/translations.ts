/**
 * Get translation for a specific language and key, with graceful fallbacks.
 */
export function getTranslation(lang: string = "en"): TranslationDict {
  const target = TRANSLATIONS[lang] ?? {};
  // For Indian languages, fallback to Hindi if available, then English
  const fallback = lang !== "en" ? { ...TRANSLATIONS.en, ...TRANSLATIONS.hi } : TRANSLATIONS.en;
  return { ...fallback, ...target } as TranslationDict;
}

/**
 * Get translated weather description for a WMO code.
 */
export function getTranslatedWeatherText(code: number | null | undefined, lang: string = "en"): string {
  if (code == null) return "Unknown";
  const dict = getTranslation(lang);
  return dict.weatherCodes?.[code] ?? DEFAULT_WEATHER_CODES[code] ?? "Clear sky";
}

/**
 * Translate weekday / relative date labels ("Today", "Tomorrow", "Sun", "Mon", etc.)
 */
export function getTranslatedDay(label: string, lang: string = "en"): string {
  const dict = getTranslation(lang);
  if (label === "Today") return dict.today;
  if (label === "Tomorrow") return dict.tomorrow;
  if (label in dict.days) return dict.days[label as keyof typeof dict.days];
  return label;
}
